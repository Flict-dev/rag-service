def _pasta_page(index: int, recipe: dict[str, object]) -> dict[str, object]:
    ingredients = "\n".join(f"- {ingredient}" for ingredient in recipe["ingredients"])
    steps = "\n".join(f"{position}. {step}" for position, step in enumerate(recipe["steps"], start=1))
    timestamp = f"2026-05-10T11:{index:02d}:00+00:00"

    return {
        "id": recipe["id"],
        "sectionId": recipe["sectionId"],
        "title": recipe["title"],
        "contentMd": (
            f"# {recipe['title']}\n\n"
            "## Профиль\n"
            f"Форма пасты: {recipe['shape']}.\n"
            f"Время приготовления: {recipe['time']}.\n"
            f"Контрольная фраза для RAG: {recipe['marker']}.\n\n"
            "## Ингредиенты\n"
            f"{ingredients}\n\n"
            "## Приготовление\n"
            f"{steps}\n\n"
            "## Подача\n"
            f"{recipe['serving']}"
        ),
        "createdAt": timestamp,
        "updatedAt": timestamp,
    }


